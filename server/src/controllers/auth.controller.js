// ================= LOGOUT =================
export const logout = async (req, res) => {
  try {
    res.cookie("token", "", {
      ...getCookieOptions(),
      expires: new Date(0),
    });

    return res.status(200).json({
      success: true,
      message: "Logged out successfully",
    });
  } catch (error) {
    console.error("Logout Error:", error);

    return res.status(500).json({
      success: false,
      message: "Logout failed.",
    });
  }
};